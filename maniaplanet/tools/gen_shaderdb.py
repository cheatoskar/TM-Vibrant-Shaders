"""Writes src/shaderdb_table.inc: the DXBC checksum of every ManiaPlanet pixel shader with its name
and a role (scene, tone map, post effect, 2D/interface).

The game hands its shaders to ID3D11Device::CreatePixelShader as DXBC; bytes 4..19 of a DXBC blob
are its checksum. The engine's compiled shaders ship in Packs/GpuCache_D3D11_SM*.zip, so the mod
can tell at run time which draw is the tone map, which is FXAA, which is the interface.

    python -I tools/gen_shaderdb.py "C:/Program Files (x86)/ManiaPlanet/Packs" > src/shaderdb_table.inc
"""
import os
import struct
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gpucache import dxbc_blobs, gbx_body, shader_kind  # noqa: E402
from rdef import rdef  # noqa: E402

SCENE, TONEMAP, POST, UI, OTHER = 1, 2, 3, 4, 5

# Textures the mod wants from the engine, by their binding name. Slots differ per shader, so each
# entry carries the slot where that shader reads it (255: doesn't). Order = ShaderEntry::slots.
SLOT_NAMES = ('TMapDeferredPixelNormalInC', 'TMapDeferredMDiffuse', 'TMapDeferredMSpecular',
              'TMapDeferredLightMask', 'TMapMotion', 'TMapDeferredDepth')

TONEMAP_KEYS = ('tonemapglobalfilmcurve', 'copycolor0_tonemapt3', 'fxtm_tonemapwithhistogramsat',
                'fxtm_globalop', 'tonemaplocalop')
POST_KEYS = ('fxaa', 'fxcolorgrading', 'fxbloom', 'motionb_', 'dof_', 'fxedgeblender', 'fxssaa', 'fxdistor',
             'fxhorizonblur', '2dflareadd', '2dlensdirt', 'fxtm_', 'tonemap_showhistogram', 'colorspc3',
             'stereo', 'occzcmp', 'rasterdistor2d', 'downsize2x2avginldr', 'downsize3x3avginldr', 'rastersum2hdrmaps', 'rastermsaaresolvehdr')
UI_KEYS = ('rasterbitmap', 'engines/media/text/phlsl/bitmap', 'bitmapmodcv', 'blendbitmap2', 'blenddebugtext',
           'rasterconst', 'rasterbink', 'texturemodcv', 'menu/', 'minimap', 'fx_debugbitmap', 'premodcolor0',
           'fillcolor', 'fillconst', 'copycolor0.')
SCENE_KEYS = ('tech3', 'techno3', 'effects/particles', 'mgrparticle', 'deferred', 'sky/', 'clouds/', 'vehicles/',
              'garage/', 'shootmania/', 'sea_', 'water', 'impostor', 'shadowcaster', 'zonly', 'smoffzone',
              'smgoaloffzone', 'smvortex', 'energy', 'lightmap/', '3dvolumetricfog')


def role(name):
    n = name.lower()
    if any(k in n for k in TONEMAP_KEYS):
        return TONEMAP
    if any(k in n for k in POST_KEYS):
        return POST
    if any(k in n for k in UI_KEYS):
        return UI
    if any(k in n for k in SCENE_KEYS):
        return SCENE
    return OTHER


def short(name):
    for cut in ('.GpuCache.Gbx', '.Txt', '.txt', '.PHlsl', '.hlsl', '.p_hlsl'):
        name = name.replace(cut, '')
    return name.replace('/Media/Text', '').replace('/PHLSL/', '/').replace('/PHlsl/', '/')


def main():
    packs = sys.argv[1]
    entries = {}
    names = []
    name_index = {}
    for z in ('GpuCache_D3D11_SM5.zip', 'GpuCache_D3D11_SM4.zip'):
        path = os.path.join(packs, z)
        if not os.path.exists(path):
            continue
        zf = zipfile.ZipFile(path)
        for entry in sorted(zf.namelist()):
            if not entry.endswith('.Gbx'):
                continue
            body = gbx_body(zf.read(entry))
            for blob in dxbc_blobs(body):
                if shader_kind(blob) != 'ps':
                    continue
                hi, lo = struct.unpack_from('<QQ', blob, 4)
                if (hi, lo) in entries:
                    continue
                bound = {n: b for t, n, b, c in rdef(blob)['resources'] if t == 'texture'}
                slots = tuple(bound.get(n, 255) if bound.get(n, 255) < 255 else 255 for n in SLOT_NAMES)
                s = short(entry)
                if s not in name_index:
                    name_index[s] = len(names)
                    names.append(s)
                entries[(hi, lo)] = (name_index[s], role(entry), slots)
    out = sys.stdout
    out.write('// Generated by tools/gen_shaderdb.py from ManiaPlanet 2019-11-19 Packs/GpuCache_D3D11_SM5.zip and\n')
    out.write('// GpuCache_D3D11_SM4.zip: DXBC checksum -> shader name, role, texture slots. Do not edit.\n')
    out.write('// clang-format off\n')
    out.write('static const char* const kShaderNames[] = {\n')
    for s in names:
        out.write('    "%s",\n' % s.replace('\\', '/').replace('"', ''))
    out.write('};\n')
    out.write('static const ShaderEntry kShaderEntries[] = {\n')
    for (hi, lo) in sorted(entries):
        idx, r, slots = entries[(hi, lo)]
        out.write('    {0x%016xull, 0x%016xull, %d, %d, {%s}},\n' % (hi, lo, idx, r, ', '.join(str(x) for x in slots)))
    out.write('};\n')
    sys.stderr.write('%d pixel shaders, %d names\n' % (len(entries), len(names)))


if __name__ == '__main__':
    main()
